"""Район по геометрии — одно правило для записи, сидов и городской сводки.

Здание, донесение, гидрант, пожарная часть и выезд относятся к району по одному
и тому же правилу — иначе суммы по районам разойдутся с итогом по городу, а
донесение, записанное с одним районом, сид потом молча перенесёт в другой:

  • район, в полигон которого геометрия попадает (ST_Contains);
  • вне всех полигонов — ближайший район по расстоянию на эллипсоиде
    (geography, метры). Объединение OSM-границ покрывает ~91% территории
    города: присоединённые земли на востоке (аэропорт) и на юге на районы не
    разбиты, и оставить их «ничьими» значило бы выронить эти объекты из
    районных цифр. Планарный `<->` в градусах здесь не годится: на широте
    Астаны градус долготы — это ~0,63 градуса широты, и «ближайший» по
    градусам район для точки к востоку или западу бывает дальним в метрах.
    Районов пять, так что точное ST_Distance по каждому дёшево.

Граница полигона не считается «внутри» для ST_Contains, поэтому точка ровно на
общей границе двух районов уходит во вторую ветку (расстояние 0) и
детерминированно достаётся району с меньшим id.

Таблица `districts` — миграция 0023, наполнение — scripts/seed_districts.py.
Используется при вставке донесений (reports.py) и зданий (import_osm.py), в
seed_districts и в /city.
"""


def district_of(geom_sql: str) -> str:
    """SQL-выражение: имя района для геометрии `geom_sql` (SRID 4326).

    `geom_sql` обязан ссылаться на столбец через алиас внешнего запроса
    (`b.geom`, `ST_PointOnSurface(src.geom)`) или на параметры: внутри
    подзапроса неквалифицированный `geom` разрешился бы в `districts.geom`.

    Вторая ветка COALESCE вычисляется только для геометрий вне всех
    полигонов — для остальных ближайший район не ищется вовсе. Пустая таблица
    districts даёт NULL.
    """
    return (
        "COALESCE("
        f"(SELECT d.name FROM districts d WHERE ST_Contains(d.geom, {geom_sql}) "
        "ORDER BY d.id LIMIT 1), "
        "(SELECT d.name FROM districts d "
        f"ORDER BY ST_Distance(d.geom::geography, ({geom_sql})::geography), d.id LIMIT 1)"
        ")"
    )
