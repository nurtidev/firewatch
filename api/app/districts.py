"""Район по геометрии — одно правило для сидов и городской сводки.

Здание, донесение, гидрант, пожарная часть и выезд относятся к району по одному
и тому же правилу — иначе суммы по районам разойдутся с итогом по городу:

  • район, в полигон которого геометрия попадает (ST_Contains);
  • вне всех полигонов — ближайший район. Объединение OSM-границ покрывает
    ~91% территории города: присоединённые земли на востоке (аэропорт) и на
    юге на районы не разбиты, и оставить их «ничьими» значило бы выронить эти
    объекты из районных цифр.

Граница полигона не считается «внутри» для ST_Contains, поэтому точка ровно на
общей границе двух районов уходит во вторую ветку (расстояние 0) и
детерминированно достаётся району с меньшим id.

Таблица `districts` — миграция 0023, наполнение — scripts/seed_districts.py.
"""


def district_of(geom_sql: str) -> str:
    """SQL-выражение: имя района для геометрии `geom_sql`.

    `geom_sql` обязан ссылаться на столбец через алиас внешнего запроса
    (`b.geom`, `ST_PointOnSurface(src.geom)`): внутри подзапроса
    неквалифицированный `geom` разрешился бы в `districts.geom`.

    Вторая ветка COALESCE вычисляется только для геометрий вне всех
    полигонов — для остальных ближайший район не ищется вовсе.
    """
    return (
        "COALESCE("
        f"(SELECT d.name FROM districts d WHERE ST_Contains(d.geom, {geom_sql}) "
        "ORDER BY d.id LIMIT 1), "
        f"(SELECT d.name FROM districts d ORDER BY d.geom <-> {geom_sql}, d.id LIMIT 1)"
        ")"
    )
