"""Расстановка оффлайн: клиентский идентификатор позиции и время постановки

Revision ID: 0021_deployment_offline
Revises: 0020_plan_positions
Create Date: 2026-08-06

На пожаре связь пропадает именно тогда, когда расстановка идёт активнее
всего — в первые минуты, в подвале, за бетоном. До этой миграции схема
честно предупреждала «связи нет, расстановка не сохраняется», и РТП должен
был запоминать позиции и ставить их заново. Теперь позиции копятся на
устройстве и уходят пачкой, когда связь появляется.

**client_uid — идентификатор позиции, выданный устройством.** Он решает две
задачи, которые иначе решаются угадыванием:

  • *Идемпотентность.* Доставка очереди — at-least-once: POST мог
    закоммититься и не донести ответ (в поле это обычный случай). Повтор с
    тем же client_uid не создаёт второй ствол на том же этаже. Тот же
    приём уже применён к донесениям с мест (`reports.client_id`).
  • *Переотображение id.* Позиция, поставленная оффлайн, серверного id не
    имеет, а её потом двигают и поворачивают. Клиент схлопывает эти правки
    в одно намерение «создать вот такую позицию», а после синхронизации
    находит её в ответе по своему же client_uid — без сопоставления по
    координатам, которое ломается, когда рядом стоят два одинаковых ствола.

Уникальность — в пределах выезда и только для непустого значения: позиции,
созданные с пульта (обычная форма), client_uid не имеют, и NULL'ы не должны
конфликтовать между собой.

**placed_at — когда позицию поставили, created_at — когда сервер её записал.**
После сорока минут без связи это разные времена, и для разбора выезда важно
первое: «ствол подан в 14:32» — факт боевых действий, «запись в 14:51» —
факт синхронизации. Клиентские часы могут врать, поэтому серверное время не
подменяется, а дополняется: расходятся они только там, где связь пропадала.
"""

